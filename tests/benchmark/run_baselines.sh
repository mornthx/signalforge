#!/usr/bin/env bash
# tests/benchmark/run_baselines.sh
#
# Configures a dedicated `release-bench` CMake build with
# -DSIGNALFORGE_BENCHMARKS=ON, runs throughput / latency / footprint,
# and writes the consolidated results to
# tests/benchmark/results/M3-baseline.md.
#
# Usage: from the repo root:
#   tests/benchmark/run_baselines.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

BUILD=build/release-bench
mkdir -p "$BUILD"

# Base on the release preset's toolchain, but add the benchmark option.
# Users with a custom Qt path should set $SIGNALFORGE_QT_PATH (falls back
# to ~/Qt/6.10.2/gcc_64).
QT_PATH="${SIGNALFORGE_QT_PATH:-$HOME/Qt/6.10.2/gcc_64}"

cmake -S "$ROOT" -B "$BUILD" \
    -GNinja \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_PREFIX_PATH="$QT_PATH" \
    -DSIGNALFORGE_BENCHMARKS=ON \
    >/dev/null
cmake --build "$BUILD" -j"$(nproc)" --target \
    bench_driver_throughput bench_driver_latency bench_driver_footprint

RESULTS_DIR="$ROOT/tests/benchmark/results"
mkdir -p "$RESULTS_DIR"
RAW_THROUGHPUT="$RESULTS_DIR/.raw_throughput.jsonl"
RAW_LATENCY="$RESULTS_DIR/.raw_latency.jsonl"
RAW_FOOTPRINT="$RESULTS_DIR/.raw_footprint.jsonl"

echo "Running throughput benchmark (~40s)..."
"$BUILD/tests/benchmark/bench_driver_throughput" >"$RAW_THROUGHPUT"

echo "Running latency benchmark (~20s)..."
"$BUILD/tests/benchmark/bench_driver_latency" >"$RAW_LATENCY"

echo "Running footprint benchmark (~10s)..."
"$BUILD/tests/benchmark/bench_driver_footprint" >"$RAW_FOOTPRINT"

OUT="$RESULTS_DIR/M3-baseline.md"
{
    echo "# M3 baseline measurements"
    echo
    echo "Generated by \`tests/benchmark/run_baselines.sh\` on $(date -u +"%Y-%m-%dT%H:%M:%SZ")."
    echo
    echo "Host: $(uname -srmp) / CPU: $(grep -c ^processor /proc/cpuinfo) logical cores"
    echo
    echo "## Throughput (raw)"
    echo '```'
    cat "$RAW_THROUGHPUT"
    echo '```'
    echo
    echo "## Latency (raw)"
    echo '```'
    cat "$RAW_LATENCY"
    echo '```'
    echo
    echo "## Footprint (raw)"
    echo '```'
    cat "$RAW_FOOTPRINT"
    echo '```'
    echo
    echo "## Threshold evaluation"
    echo
    echo "Each benchmark's category classification (per spec §5.5) is filled in"
    echo "manually after running this script; see the adjoining commit message."
} >"$OUT"

echo "Done. Results at $OUT"
